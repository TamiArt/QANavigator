export type TranslationKey = keyof typeof translations.en;

export function translate(language: Language, key: TranslationKey): string {
  return translations[language][key] ?? translations.en[key] ?? key;
}

export function getModuleTitle(language: Language, id: string, fallback: string): string {
  const key = `module.${id}` as TranslationKey;
  return key in translations.en && language === "en" ? translate(language, key) : fallback;
}

export function getLessonTitle(language: Language, id: string, fallback: string): string {
  const key = `lesson.${id}.title` as TranslationKey;
  return key in translations.en && language === "en" ? translate(language, key) : fallback;
}

