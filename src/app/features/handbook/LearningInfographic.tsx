function PdfDownloadButton({ targetId, imagePath, language = "ru" }: { targetId: string; imagePath?: string; language?: Language }) {
  const [isGenerating, setIsGenerating] = React.useState(false);
  const [error, setError] = React.useState("");

  const downloadPdf = async () => {
    const target = document.getElementById(targetId);
    if (!target || isGenerating) return;
    setIsGenerating(true);
    setError("");
    try {
      if (imagePath) {
        const link = document.createElement("a");
        link.href = imagePath;
        link.download = decodeURIComponent(imagePath.split("/").pop() || "infographic");
        link.style.display = "none";
        document.body.appendChild(link);
        link.click();
        link.remove();
        return;
      }
      const [{ jsPDF }, html2canvasModule] = await Promise.all([
        import("jspdf"),
        import("html2canvas"),
      ]);
      const canvas = await html2canvasModule.default(target, {
        backgroundColor: "#ffffff",
        scale: Math.min(2, window.devicePixelRatio || 1),
        useCORS: true,
        ignoreElements: (element) => element.hasAttribute("data-pdf-ignore"),
      });
      const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
      const pageWidth = pdf.internal.pageSize.getWidth();
      const pageHeight = pdf.internal.pageSize.getHeight();
      const imageWidth = pageWidth;
      const imageHeight = (canvas.height * imageWidth) / canvas.width;
      const image = canvas.toDataURL("image/png", 1);
      if (imageHeight <= pageHeight) {
        pdf.addImage(image, "PNG", 0, 0, imageWidth, imageHeight);
      } else {
        let sourceY = 0;
        const pagePixelHeight = Math.floor((pageHeight / imageWidth) * canvas.width);
        let pageIndex = 0;
        while (sourceY < canvas.height) {
          const sliceHeight = Math.min(pagePixelHeight, canvas.height - sourceY);
          const pageCanvas = document.createElement("canvas");
          pageCanvas.width = canvas.width;
          pageCanvas.height = sliceHeight;
          pageCanvas.getContext("2d")?.drawImage(canvas, 0, sourceY, canvas.width, sliceHeight, 0, 0, canvas.width, sliceHeight);
          if (pageIndex > 0) pdf.addPage();
          const sliceMmHeight = (sliceHeight * imageWidth) / canvas.width;
          pdf.addImage(pageCanvas.toDataURL("image/png", 1), "PNG", 0, 0, imageWidth, sliceMmHeight);
          sourceY += sliceHeight;
          pageIndex += 1;
        }
      }
      const blob = pdf.output("blob");
      const downloadUrl = URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = downloadUrl;
      link.download = "qa-navigator-visual-cheatsheet.pdf";
      link.style.display = "none";
      document.body.appendChild(link);
      link.click();
      link.remove();
      window.setTimeout(() => URL.revokeObjectURL(downloadUrl), 1000);
    } catch (error) {
      console.error("Не удалось сохранить инфографику:", error);
      setError(language === "en" ? "Could not save the file. Please try again." : "Не удалось сохранить файл. Попробуйте ещё раз.");
    } finally {
      setIsGenerating(false);
    }
  };

  return (
    <>
    <button
      type="button"
      data-pdf-ignore
      onClick={downloadPdf}
      disabled={isGenerating}
      aria-label={language === "en" ? (imagePath ? "Download infographic image" : "Save infographic as PDF") : (imagePath ? "Скачать файл инфографики" : "Сохранить инфографику в PDF")}
      title={language === "en" ? (imagePath ? "Download original infographic" : "Save infographic as PDF") : (imagePath ? "Скачать исходный файл инфографики" : "Сохранить инфографику в PDF")}
      className="inline-flex h-8 items-center gap-1.5 rounded-lg border border-blue-200 bg-white px-2.5 text-[10px] font-bold text-blue-800 shadow-sm transition hover:bg-blue-50 disabled:cursor-wait disabled:opacity-60"
    >
      <Download className="h-3.5 w-3.5" aria-hidden="true" />
      <span>{isGenerating ? (language === "en" ? "Saving…" : "Сохранение…") : (language === "en" ? "Save" : "Сохранить")}</span>
    </button>
      {error ? <span className="ml-2 text-[10px] font-semibold text-red-600" role="alert">{error}</span> : null}
    </>
  );
}

